"""Write code/m1pc/m1score.py: a standalone copy (numpy only) of the repository's M1 scoring functions, taken verbatim with
inspect.getsource, so the HPC scores exactly as our pipeline does. Re-run after any change to the originals:

    python scripts/m1/hpc_pathcrf/make_m1score.py [--check]
"""
from __future__ import annotations

import argparse
import inspect
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))                     # scripts/m1

from barca_labels import scoring as S  # noqa: E402

import c3v4  # noqa: E402
import diag_v2  # noqa: E402
import spells_v3  # noqa: E402

OUT = HERE / "code" / "m1pc" / "m1score.py"
FUNCS = [(S, n) for n in ("match_events", "change_events", "dead_events", "f1", "score", "had", "_spells", "score_had", "merge_had",
                          "merge")] + [(diag_v2, "tolerant_hits"), (spells_v3, "matched_true"), (spells_v3, "recall_by_length"),
                                       (spells_v3, "merge_recall"), (c3v4, "restart_metrics")]


def build() -> str:
    from barca_labels.labeller import CONTROL, DEAD, TOLERANCE_S
    head = f'''"""GENERATED by scripts/m1/hpc_pathcrf/make_m1score.py - do not edit. Verbatim copies of the M1 scoring functions of the
repository (m1_labels.scoring, scripts/m1/diag_v2.py, spells_v3.py, c3v4.py) so the HPC scores exactly as our pipeline does."""
from __future__ import annotations

import numpy as np

DEAD, CONTROL, TOLERANCE_S = {DEAD}, {CONTROL}, {TOLERANCE_S}
HAD_IOUS = {S.HAD_IOUS!r}
LEN_BINS = (0.0, 2.0, 5.0, 15.0, np.inf)
LEN_NAMES = {spells_v3.LEN_NAMES!r}
'''
    assert spells_v3.LEN_BINS == (0.0, 2.0, 5.0, 15.0, float("inf"))
    body = "\n\n".join(inspect.getsource(getattr(mod, n)) for mod, n in FUNCS)
    return head + "\n\n" + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    a = ap.parse_args()
    txt = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == txt
        print("m1score.py up to date" if ok else "m1score.py OUT OF DATE")
        return 0 if ok else 1
    OUT.write_text(txt, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
